import { bundledLanguagesInfo } from "shiki/langs";

/** A language as Shiki ships it: its id, its aliases and the file types its grammar names. */
export interface ShikiLanguage {
  id: string;
  aliases: readonly string[];
  fileTypes: readonly string[];
}

/** The tables `catalog.gen.ts` holds, every key in lower case and every value a language id. */
export interface Catalog {
  names: Record<string, string>;
  extensions: Record<string, string>;
}

/** Every language Shiki ships, with the file types of its grammar; each grammar is imported once to read them. */
export async function shikiLanguages(): Promise<ShikiLanguage[]> {
  return Promise.all(
    bundledLanguagesInfo.map(async (info) => {
      const { default: registrations } = await info.import();
      const own = registrations.find((r) => r.name === info.id);
      return {
        id: info.id,
        aliases: info.aliases ?? [],
        fileTypes: own?.fileTypes ?? [],
      };
    }),
  );
}

function sorted(entries: Iterable<[string, string]>): Record<string, string> {
  return Object.fromEntries(
    [...entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
  );
}

/**
 * A grammar's file types are suffixes of a file name. Several grammars claim some of them, such as `conf` or `s`; such
 * a type, and one that is a language's id or alias, is left out, so a name never resolves by the order of the grammars.
 */
export function buildCatalog(languages: readonly ShikiLanguage[]): Catalog {
  const names = new Map<string, string>();
  for (const { id, aliases } of languages) {
    names.set(id, id);
    for (const alias of aliases) names.set(alias.toLowerCase(), id);
  }
  const claims = new Map<string, Set<string>>();
  for (const { id, fileTypes } of languages) {
    for (const fileType of fileTypes) {
      const suffix = fileType.toLowerCase().replace(/^\./, "");
      if (suffix === "" || /[\s/]/.test(suffix) || names.has(suffix)) continue;
      const claimed = claims.get(suffix) ?? new Set<string>();
      claimed.add(id);
      claims.set(suffix, claimed);
    }
  }
  const extensions: [string, string][] = [];
  for (const [suffix, ids] of claims) {
    const [only] = ids;
    if (ids.size === 1 && only !== undefined) extensions.push([suffix, only]);
  }
  return { names: sorted(names), extensions: sorted(extensions) };
}

function table(entries: Record<string, string>): string {
  const lines = Object.entries(entries).map(
    ([key, id]) => `  ${JSON.stringify(key)}: ${JSON.stringify(id)},`,
  );
  return `{\n${lines.join("\n")}\n}`;
}

/** The source of `catalog.gen.ts`. */
export function renderCatalog(catalog: Catalog): string {
  return `// Generated by \`make gen-languages\` from the installed Shiki. A test fails when it differs from Shiki's data.
import type { BundledLanguage } from "shiki/langs";

/** Every language id and alias, to the id. */
export const NAMES: Readonly<Record<string, BundledLanguage>> = ${table(catalog.names)};

/** The file types that exactly one grammar claims and that name no language, to that grammar's id. */
export const EXTENSIONS: Readonly<Record<string, BundledLanguage>> = ${table(catalog.extensions)};
`;
}
